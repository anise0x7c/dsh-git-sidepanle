import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { cp, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const manifest: {
  packageManager: string
  dependencies?: Record<string, string>
  exports: Record<string, string>
  files: string[]
  scripts: Record<string, string>
} = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
const tsconfig: {
  compilerOptions?: Record<string, unknown>
  include?: string[]
} = JSON.parse(await readFile(new URL('../tsconfig.json', import.meta.url), 'utf8'))

test('the typecheck gate keeps the strict rules the tests rely on', () => {
  assert.equal(tsconfig.compilerOptions?.strict, true)
  assert.equal(tsconfig.compilerOptions?.exactOptionalPropertyTypes, true)
  assert.equal(tsconfig.compilerOptions?.noUncheckedIndexedAccess, true)
  const included = tsconfig.include ?? []
  for (const directory of ['src', 'scripts', 'test']) {
    assert.ok(
      included.some((pattern) => pattern.startsWith(`${directory}/`)),
      `tsconfig.json must typecheck ${directory}`,
    )
  }
})

test('the maintenance gate checks without rebuilding or rewriting sources', () => {
  assert.match(manifest.packageManager, /^pnpm@\d+\.\d+\.\d+$/)
  assert.equal(
    manifest.scripts.check,
    'pnpm typecheck && pnpm lint && pnpm test:run && pnpm check:build',
  )
  const testRun = manifest.scripts['test:run']
  assert.ok(testRun !== undefined, 'the maintenance gate defines test:run')
  assert.doesNotMatch(testRun, /(?:^|&&\s*)pnpm build/)
  const checkBuild = manifest.scripts['check:build']
  assert.ok(checkBuild !== undefined, 'the maintenance gate defines check:build')
  assert.match(checkBuild, /--check/)
  assert.equal(manifest.scripts.precheck, undefined)
  assert.equal(manifest.scripts['pretest:run'], undefined)
  assert.deepEqual(manifest.dependencies ?? {}, {})
})

test('all authored executable source, test and script files are TypeScript', async () => {
  async function verify(directory: string): Promise<void> {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const file = path.join(directory, entry.name)
      if (entry.isDirectory()) await verify(file)
      else assert.doesNotMatch(file, /\.(?:[cm]?js|jsx)$/, `unmigrated authored code: ${file}`)
    }
  }
  for (const directory of ['src', 'scripts', 'test']) await verify(path.join(root, directory))
})

test('both committed maps contain TypeScript sources and no bundled dependencies', async () => {
  for (const name of ['index.js', 'client.js']) {
    assert.ok(manifest.files.includes(name))
    assert.ok(manifest.files.includes(`${name}.map`))
    const artifact = await readFile(path.join(root, name), 'utf8')
    const map: { sources: string[]; sourcesContent: string[] } = JSON.parse(
      await readFile(path.join(root, `${name}.map`), 'utf8'),
    )
    assert.match(artifact, /generated by scripts\/build\.ts/)
    assert.ok(map.sources.some((source) => source.endsWith('.ts')))
    assert.ok(map.sources.every((source) => !source.includes('node_modules')))
    assert.equal(map.sourcesContent.length, map.sources.length)
    assert.ok(
      map.sourcesContent.every((content) => typeof content === 'string' && content.length > 0),
    )
  }
  assert.equal(manifest.exports['.'], './index.js')
  assert.equal(manifest.exports['./client'], './client.js')
})

test('the distributed Host entry loads and disposes without a compiler or node_modules', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'dsh-git-sidepanel-artifact-'))
  try {
    await cp(path.join(root, 'index.js'), path.join(directory, 'index.js'))
    await writeFile(path.join(directory, 'package.json'), '{"type":"module"}\n')
    const program = `
      import assert from 'node:assert/strict'
      import { inject, apply } from './index.js'
      assert.deepEqual(inject, ['webServer'])
      const routes = new Map()
      const cleanup = apply({
        effect: (setup) => setup(),
        webServer: { register: (route) => {
          routes.set(route.path, route)
          return () => routes.delete(route.path)
        } },
        get: () => undefined,
      })
      assert.equal(routes.size, 2)
      assert.ok(routes.has('/api/dsh-git-sidepanel/rpc'))
      assert.ok(routes.has('/api/dsh-git-sidepanel/health'))
      cleanup()
      assert.equal(routes.size, 0)
    `
    execFileSync(process.execPath, ['--input-type=module', '--eval', program], {
      cwd: directory,
      env: { ...process.env, NODE_OPTIONS: '', NODE_PATH: '' },
      stdio: 'pipe',
    })
  } finally {
    // Only this exact mkdtemp-owned directory is eligible for cleanup.
    assert.equal(path.dirname(directory), tmpdir())
    assert.ok(path.basename(directory).startsWith('dsh-git-sidepanel-artifact-'))
    await rm(directory, { recursive: true, force: true })
  }
})
